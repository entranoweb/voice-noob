"""Audio of a caller call: one row per side per call, the bytes live in the audio store.

The database holds only what is needed to find, serve and expire a file. The
bytes are in the audio store (``app.services.audio_store``), under a key this
code generated; no name or path the uploader sent is kept anywhere.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, Float, ForeignKey, Integer, String, UniqueConstraint, Uuid
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, TimestampMixin

# The two sides of a call, as the caller names them. "caller" is the audio the
# rig played; "agent" is what came back from the agent.
TRACKS = ("caller", "agent")


class CallerAudio(Base, TimestampMixin):
    """One recording (one side of one call) held in the audio store."""

    __tablename__ = "caller_audio"
    __table_args__ = (UniqueConstraint("call_id", "track", name="uq_caller_audio_call_track"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid(as_uuid=True), primary_key=True, default=uuid.uuid4)
    workspace_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("workspaces.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    run_pk: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("caller_runs.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    call_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("caller_calls.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    track: Mapped[str] = mapped_column(String(16), nullable=False)
    # Generated by the store: "<workspace id>/<random hex>.wav". Never client input.
    storage_key: Mapped[str] = mapped_column(String(120), nullable=False)
    size_bytes: Mapped[int] = mapped_column(Integer, nullable=False)
    duration_s: Mapped[float] = mapped_column(Float, nullable=False)
    sample_rate: Mapped[int] = mapped_column(Integer, nullable=False)
    channels: Mapped[int] = mapped_column(Integer, nullable=False)
    sha256: Mapped[str] = mapped_column(String(64), nullable=False)
    # Set when retention deleted the file. The row stays as a record that there
    # was a recording and that it expired, so the call page can say so instead
    # of looking as if nothing was ever recorded.
    expired_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    def __repr__(self) -> str:
        return f"<CallerAudio {self.id} {self.track}>"
